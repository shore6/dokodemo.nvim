#!/usr/bin/env python3
"""Generate lua/dokodemo/kanji.lua from Unihan kJapanese readings.

Usage:
    python3 scripts/gen_kanji.py path/to/Readings.db > lua/dokodemo/kanji.lua

`Readings.db` is the SQLite version of Unihan_Readings.txt shipped in the
`kanji-inspector` npm package (dist/db/Readings.db). Only kanji encodable in
JIS X 0208 (Shift_JIS) are kept to keep the table small.
"""
import sqlite3
import sys


def kata_to_hira(s):
    return "".join(chr(ord(c) - 0x60) if 0x30A1 <= ord(c) <= 0x30F6 else c for c in s)


def main(db_path):
    conn = sqlite3.connect(db_path)
    rows = conn.execute(
        "SELECT codepoint, kJapanese FROM Readings WHERE kJapanese IS NOT NULL AND kJapanese != '' ORDER BY codepoint"
    )
    out = [
        "-- Generated by scripts/gen_kanji.py. Do not edit by hand.",
        "-- Readings: Unicode Unihan database (kJapanese), Unicode License v3.",
        "-- Format: on-readings | kun-readings (hiragana, space separated).",
        "return {",
    ]
    for cp, reading in rows:
        ch = chr(cp)
        try:
            ch.encode("shift_jis")
        except UnicodeEncodeError:
            continue
        on, kun = [], []
        for r in reading.split():
            if any(0x30A1 <= ord(c) <= 0x30FC for c in r):
                v = kata_to_hira(r)
                if v not in on:
                    on.append(v)
            elif v := r.replace("-", "").replace(".", ""):
                if v not in kun:
                    kun.append(v)
        if not on and not kun:
            continue
        out.append('["%s"]="%s|%s",' % (ch, " ".join(on), " ".join(kun)))
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
